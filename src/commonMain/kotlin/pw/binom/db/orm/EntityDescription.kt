package pw.binom.db.orm

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.KSerializer
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.SerialKind
import kotlinx.serialization.descriptors.StructureKind
import pw.binom.db.DatabaseEngine

/**
 * Описание сущности, собранное по [SerialDescriptor].
 *
 * ## Зачем разбирать дескриптор
 *
 * Рефлексии в Kotlin/Native нет. Единственный переносимый источник
 * метаданных — `SerialDescriptor`, который генерирует плагин
 * `kotlinx.serialization`. Аннотации читаются из него, если помечены
 * `@SerialInfo` — поэтому все аннотации ORM такие.
 *
 * ## Почему один раз
 *
 * Разбор дескриптора небыстрый: рекурсия по элементам, чтение аннотаций.
 * Генерация SQL идёт на каждый запрос, поэтому описание строится однажды и
 * кэшируется вызывающим (см. [EntityCache]).
 */
class EntityDescription(
    /** Имя таблицы: из `@TableName` или из `serialName`. */
    val tableName: String,
    /** Нужно ли экранировать имя таблицы. */
    val tableQuoted: Boolean,
    /** Колонки в порядке объявления полей. */
    val columns: List<Column>,
    /** Поля первичного ключа. Пусто, если `@Id` не указан. */
    val idColumns: List<Column>,
    val indexes: List<IndexDescription> = emptyList(),
) {
    /** Колонки, которые БД назначает сама: исключаются из INSERT и UPDATE. */
    val generatedColumns: List<Column> get() = columns.filter { it.autoGenerated }

    /** Колонки для INSERT: всё, кроме сгенерированных. */
    val insertColumns: List<Column> get() = columns.filter { !it.autoGenerated }

    /** Колонки для UPDATE: всё, кроме сгенерированных и ключей. */
    val updateColumns: List<Column>
        get() = columns.filter { !it.autoGenerated && !it.isId }

    /** Колонка сущности. */
    class Column(
        /** Имя в объекте Kotlin — по нему берётся значение из сериализатора. */
        val propertyName: String,
        /** Имя колонки в БД. */
        val columnName: String,
        /** Номер элемента в `SerialDescriptor`. */
        val index: Int,
        val isId: Boolean,
        val autoGenerated: Boolean,
        val quoted: Boolean,
        /** Явный тип из `@ColumnType`/`@PgColumnType`/`@SqliteColumnType`. */
        val explicitType: String?,
        /** Вложенный объект: его поля становятся колонками с этим префиксом. */
        val embeddedPrefix: String?,
        /** Вложенное описание, если поле `@Embedded`. */
        val embedded: EntityDescription?,
        /**
         * Путь к полю в объекте, через точку: `address.city`.
         *
         * Нужен для сопоставления со значениями из `ValueEncoder`, который
         * ключует именно так. **Не то же самое, что [embeddedPrefix]**:
         * префикс — это имя колонки в БД (`home_`), а путь — имя поля в
         * классе (`address`). Совпадают они только если `@EmbeddedPrefix`
         * не задан.
         */
        val objectPath: String,
        /**
         * Вид значения по `SerialKind` — нужен для вывода типа колонки,
         * когда `@ColumnType` не задан.
         */
        val kind: SerialKind,
    ) {
        /** Итоговое имя в БД с учётом префикса вложенного объекта. */
        val fullColumnName: String
            get() = if (embeddedPrefix != null) "$embeddedPrefix$columnName" else columnName
    }

    class IndexDescription(
        val name: String,
        val unique: Boolean,
        val columns: List<String>,
    )

    companion object {
        /**
         * Собирает описание по сериализатору.
         *
         * `engine` нужен для выбора типа колонки там, где тип по умолчанию
         * зависит от СУБД (SQLite почти всё хранит строкой).
         */
        @OptIn(ExperimentalSerializationApi::class)
        fun of(
            serializer: KSerializer<*>,
            engine: DatabaseEngine,
            tableNameOverride: String? = null,
            prefix: String? = null,
        ): EntityDescription = of(serializer.descriptor, engine, tableNameOverride, prefix)

        /**
         * Перегрузка для [SerialDescriptor].
         *
         * Нужна для вложенных объектов: `@Embedded` приходит дескриптором
         * (`getElementDescriptor`), а не сериализатором — сериализатор поля
         * доступен только через `descriptor.getElementDescriptor`, и обратно
         * к `KSerializer` не ведёт.
         */
        @OptIn(ExperimentalSerializationApi::class)
        fun of(
            d: SerialDescriptor,
            engine: DatabaseEngine,
            tableNameOverride: String? = null,
            prefix: String? = null,
        ): EntityDescription {

            val tableAnn = d.annotations.filterIsInstance<TableName>().firstOrNull()
            val tableQuoted = d.annotations.any { it is UseQuotes }
            val name = tableNameOverride ?: tableAnn?.tableName ?: d.serialName.substringAfterLast('.')

            val cols = mutableListOf<Column>()
            collectColumns(d, engine, prefix, null, cols)

            val ids = cols.filter { it.isId }

            val indexes = mutableListOf<IndexDescription>()
            for (ann in d.annotations) {
                when (ann) {
                    is Index -> indexes += IndexDescription(
                        name = ann.name.ifEmpty { "${name}_${ann.columns.joinToString("_")}_idx" },
                        unique = ann.unique,
                        columns = ann.columns.toList(),
                    )
                    is Indexes -> ann.indexes.forEach { ix ->
                        indexes += IndexDescription(
                            name = ix.name.ifEmpty { "${name}_${ix.columns.joinToString("_")}_idx" },
                            unique = ix.unique,
                            columns = ix.columns.toList(),
                        )
                    }
                }
            }

            return EntityDescription(
                tableName = name,
                tableQuoted = tableQuoted,
                columns = cols,
                idColumns = ids,
                indexes = indexes,
            )
        }

        /**
         * Обходит дескриптор, разворачивая `@Embedded`.
         *
         * `SerialKind.CONTEXTUAL` пропускается: значение такого поля ORM
         * сериализовать не умеет и не должна притворяться, что умеет.
         */
        @OptIn(ExperimentalSerializationApi::class)
        private fun collectColumns(
            d: SerialDescriptor,
            engine: DatabaseEngine,
            prefix: String?,
            objectPath: String?,
            out: MutableList<Column>,
        ) {
            for (i in 0 until d.elementsCount) {
                val el = d.getElementDescriptor(i)
                val elName = d.getElementName(i)
                val anns = d.getElementAnnotations(i)

                val embedded = anns.any { it is Embedded }
                if (embedded && el.kind == StructureKind.CLASS) {
                    val embPrefix = anns.filterIsInstance<EmbeddedPrefix>().firstOrNull()?.prefix ?: prefix
                    // Путь в объекте дополняется именем поля, префикс колонки —
                    // из аннотации. Это разные вещи, и путать их значит
                    // потерять значения при записи.
                    val newPath = if (objectPath == null) elName else "$objectPath.$elName"
                    collectColumns(el, engine, embPrefix, newPath, out)
                    continue
                }

                if (el.kind == SerialKind.CONTEXTUAL) continue

                val columnName = anns.filterIsInstance<ColumnName>().firstOrNull()?.columnName ?: elName
                val explicit = anns.filterIsInstance<PgColumnType>().firstOrNull()?.type
                    ?: anns.filterIsInstance<SqliteColumnType>().firstOrNull()?.type
                    ?: anns.filterIsInstance<ColumnType>().firstOrNull()?.type

                out += Column(
                    propertyName = elName,
                    columnName = columnName,
                    index = i,
                    isId = anns.any { it is Id },
                    autoGenerated = anns.any { it is AutoGenerated },
                    quoted = anns.any { it is UseQuotes },
                    explicitType = explicit,
                    embeddedPrefix = prefix,
                    embedded = if (embedded) of(el, engine, null, prefix) else null,
                    kind = el.kind,
                    objectPath = if (objectPath == null) elName else "$objectPath.$elName",
                )
            }
        }
    }
}
