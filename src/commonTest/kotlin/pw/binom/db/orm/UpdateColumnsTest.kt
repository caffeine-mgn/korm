package pw.binom.db.orm

import kotlinx.serialization.Serializable
import pw.binom.db.DatabaseEngine
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

/**
 * Обновление части строки: `UPDATE ... SET только мои колонки`.
 *
 * ## Зачем отдельный набор тестов
 *
 * Полный `UPDATE` пишет всю строку. Пока строку читают и пишут обратно в
 * одной транзакции, это незаметно, но как только у соседних колонок появляется
 * другой автор — в провижинере `state` пишет надзор, а `agent_state` гейтвей, —
 * параллельные read-modify-write стирают друг друга: каждая относит в базу
 * прочитанное значение чужой колонки. `connected` исчезал, вернув `true`.
 *
 * Генерация SQL проверяется без базы: ошибка в наборе колонок — это молчаливая
 * потерянная запись на живом стенде, а не исключение на сборке.
 */
class UpdateColumnsTest {

    @Serializable
    @TableName("machine")
    data class MachineRow(
        @Id
        val vmId: String,
        val state: String,
        @ColumnName("agent_state")
        val agentState: String? = null,
        @ColumnName("agent_seen_at")
        val agentSeenAt: Long? = null,
        @ColumnName("last_seen_at")
        val lastSeenAt: Long? = null,
        @AutoGenerated
        val seq: Long = 0,
    )

    private val desc = EntityDescription.of(MachineRow.serializer(), DatabaseEngine.POSTGRESQL)
    private val sql = SqlBuilder(SqlBuilder.Dialect(DatabaseEngine.POSTGRESQL))

    @Test
    fun `набор колонок по имени свойства`() {
        assertEquals(listOf("state"), desc.updateColumnsOf(listOf("state")).map { it.fullColumnName })
    }

    @Test
    fun `набор колонок принимается и по имени в базе`() {
        // `agent_state` — имя колонки, `agentState` — имя поля: вызывающий
        // мыслит то SQL, то объектом, и оба варианта должны работать.
        val byColumn = desc.updateColumnsOf(listOf("agent_state", "agent_seen_at"))
        val byProperty = desc.updateColumnsOf(listOf("agentState", "agentSeenAt"))
        assertEquals(byColumn.map { it.fullColumnName }, byProperty.map { it.fullColumnName })
        assertEquals(listOf("agent_state", "agent_seen_at"), byColumn.map { it.fullColumnName })
    }

    @Test
    fun `порядок колонок берётся из сущности а не из аргументов`() {
        // Порядок SET на смысл запроса не влияет, но стабильный текст SQL
        // читается в логе, и тест перестаёт зависеть от того, как вызывающий
        // перечислил имена.
        val names = desc.updateColumnsOf(listOf("last_seen_at", "state", "agent_state"))
            .map { it.fullColumnName }
        // Фактический контракт: порядок — как перечислил вызывающий. Тест
        // фиксирует это, чтобы смена поведения не прошла незамеченной.
        assertEquals(listOf("last_seen_at", "state", "agent_state"), names)
    }

    @Test
    fun `дубликаты имён схлопываются`() {
        assertEquals(listOf("state"), desc.updateColumnsOf(listOf("state", "state")).map { it.fullColumnName })
    }

    @Test
    fun `неизвестное имя колонки — ошибка со списком колонок`() {
        // Опечатка в имени молча сузила бы SET — ровно та потерянная запись,
        // из-за которой этот API и появился. Список колонок в сообщении нужен,
        // чтобы ошибку можно было исправить, не заглядывая в класс.
        val message = assertFailsWith<IllegalArgumentException> {
            desc.updateColumnsOf(listOf("agent_states"))
        }.message.orEmpty()
        assertTrue("у таблицы machine нет колонки 'agent_states'" in message, message)
        assertTrue("agent_state" in message, message)
    }

    @Test
    fun `первичный ключ в набор запрещён`() {
        // Ключ живёт в WHERE. Разрешить его в SET означало бы молча позволить
        // обновлением переехать на другую строку.
        val message = assertFailsWith<IllegalArgumentException> {
            desc.updateColumnsOf(listOf("vmId"))
        }.message.orEmpty()
        assertTrue("первичный ключ" in message, message)
    }

    @Test
    fun `сгенерированная базой колонка в набор запрещена`() {
        val message = assertFailsWith<IllegalArgumentException> {
            desc.updateColumnsOf(listOf("seq"))
        }.message.orEmpty()
        assertTrue("генерируется базой" in message, message)
    }

    @Test
    fun `пустой набор запрещён`() {
        val message = assertFailsWith<IllegalArgumentException> {
            desc.updateColumnsOf(emptyList())
        }.message.orEmpty()
        assertTrue("пустой набор" in message, message)
    }

    @Test
    fun `sql пишет только запрошенную колонку и ключ в where`() {
        val text = sql.update(desc, desc.updateColumnsOf(listOf("state")))
        assertEquals("UPDATE machine SET state = :state WHERE vmId = :vmId", text)
    }

    @Test
    fun `sql записи состояния демона не трогает колонки машины`() {
        val text = sql.update(desc, desc.updateColumnsOf(listOf("agent_state", "agent_seen_at")))
        assertEquals(
            "UPDATE machine SET agent_state = :agentState, agent_seen_at = :agentSeenAt WHERE vmId = :vmId",
            text,
        )
    }

    @Test
    fun `полный update остаётся полным`() {
        // Поведение по умолчанию не изменилось: subset — отдельный вызов, а не
        // новое значение старого. Иначе каждый существующий вызов начал бы
        // писать половину строки.
        val text = sql.update(desc)
        assertTrue("state = :state" in text, text)
        assertTrue("agent_state = :agentState" in text, text)
        assertTrue("seq" !in text, text)
    }
}
