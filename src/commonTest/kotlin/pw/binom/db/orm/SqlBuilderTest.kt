package pw.binom.db.orm

import kotlinx.serialization.builtins.serializer
import pw.binom.db.DatabaseEngine
import pw.binom.db.SqlValue
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/**
 * Тесты генерации SQL.
 *
 * БД не нужна: это чистое построение строк по дескриптору. Ошибка здесь
 * даёт неверный SQL — то есть падение в рантайме на живом сервере, а не
 * при сборке. Поэтому проверяется каждое правило.
 */
class SqlBuilderTest {

    private val pg = SqlBuilder.Dialect(DatabaseEngine.POSTGRESQL)
    private val lite = SqlBuilder.Dialect(DatabaseEngine.SQLITE)

    private fun desc(engine: DatabaseEngine = DatabaseEngine.POSTGRESQL) =
        EntityDescription.of(User.serializer(), engine)

    @Test
    fun `имя таблицы из TableName`() {
        assertEquals("users", desc().tableName)
    }

    @Test
    fun `колонки в порядке полей с ColumnName`() {
        val e = desc()
        assertEquals(listOf("id", "name", "email_addr", "active", "score"), e.columns.map { it.fullColumnName })
    }

    @Test
    fun `autoGenerated исключается из insert`() {
        val e = desc()
        assertEquals(listOf("name", "email_addr", "active", "score"), e.insertColumns.map { it.fullColumnName })
    }

    @Test
    fun `autoGenerated и id исключаются из update`() {
        val e = desc()
        assertEquals(listOf("name", "email_addr", "active", "score"), e.updateColumns.map { it.fullColumnName })
    }

    @Test
    fun `insert строит именованные параметры`() {
        // Параметр называется по имени поля (`:email`), а колонка — по имени
        // в БД (`email_addr`): имена в SQL и в объекте могут не совпадать, и
        // путать их значит подставлять значения не туда.
        val sql = SqlBuilder(pg).insert(desc())
        assertEquals(
            "INSERT INTO users (name, email_addr, active, score) VALUES (:name, :email, :active, :score)",
            sql,
        )
    }

    @Test
    fun `select перечисляет все колонки`() {
        val sql = SqlBuilder(pg).select(desc())
        assertEquals("SELECT id, name, email_addr, active, score FROM users", sql)
    }

    @Test
    fun `selectById по первичному ключу`() {
        val sql = SqlBuilder(pg).selectById(desc())
        assertEquals("SELECT id, name, email_addr, active, score FROM users WHERE id = :id", sql)
    }

    @Test
    fun `update с параметрами и where`() {
        val sql = SqlBuilder(pg).update(desc())
        assertEquals(
            "UPDATE users SET name = :name, email_addr = :email, active = :active, score = :score WHERE id = :id",
            sql,
        )
    }

    @Test
    fun `upsert с ON CONFLICT`() {
        val sql = SqlBuilder(pg).upsert(desc())
        assertTrue(sql.startsWith("INSERT INTO users"), sql)
        assertTrue(sql.contains("ON CONFLICT (id) DO UPDATE SET"), sql)
        assertTrue(sql.contains("name = excluded.name"), sql)
    }

    @Test
    fun `upsert без update-колонок даёт DO NOTHING`() {
        val sql = SqlBuilder(pg).upsert(desc(), updateColumns = emptyList())
        assertTrue(sql.endsWith("ON CONFLICT (id) DO NOTHING"), sql)
    }

    @Test
    fun `deleteById`() {
        val sql = SqlBuilder(pg).deleteById(desc())
        assertEquals("DELETE FROM users WHERE id = :id", sql)
    }

    @Test
    fun `createTable postgres - BIGSERIAL для сгенерированного ключа`() {
        val sql = SqlBuilder(pg).createTable(desc())
        assertTrue(sql.contains("id BIGSERIAL PRIMARY KEY"), sql)
        assertTrue(sql.contains("IF NOT EXISTS"), sql)
    }

    @Test
    fun `createTable sqlite - INTEGER плюс AUTOINCREMENT`() {
        val sql = SqlBuilder(lite).createTable(desc(DatabaseEngine.SQLITE))
        assertTrue(sql.contains("id INTEGER PRIMARY KEY AUTOINCREMENT"), sql)
    }

    @Test
    fun `createTable sqlite - BOOLEAN становится INTEGER`() {
        val sql = SqlBuilder(lite).createTable(desc(DatabaseEngine.SQLITE))
        assertTrue(sql.contains("active INTEGER"), sql)
    }

    @Test
    fun `pgColumnType главнее columnType`() {
        val e = EntityDescription.of(TypedEntity.serializer(), DatabaseEngine.POSTGRESQL)
        val payload = e.columns.first { it.propertyName == "payload" }
        assertEquals("JSONB", payload.explicitType)

        val code = e.columns.first { it.propertyName == "code" }
        assertEquals("VARCHAR(64)", code.explicitType)
    }

    @Test
    fun `UseQuotes экранирует колонку`() {
        val e = EntityDescription.of(KeywordEntity.serializer(), DatabaseEngine.POSTGRESQL)
        val sql = SqlBuilder(pg).select(e)
        assertTrue(sql.contains("\"order\""), sql)
    }

    @Test
    fun `embedded разворачивается в колонки с префиксом`() {
        val e = EntityDescription.of(Person.serializer(), DatabaseEngine.POSTGRESQL)
        assertEquals(
            listOf("id", "name", "home_city", "home_street"),
            e.columns.map { it.fullColumnName },
        )
    }

    @Test
    fun `индекс из аннотации Index`() {
        val e = EntityDescription.of(Order.serializer(), DatabaseEngine.POSTGRESQL)
        assertEquals(1, e.indexes.size)
        assertEquals("orders_user_idx", e.indexes[0].name)
        assertFalse(e.indexes[0].unique)

        val sql = SqlBuilder(pg).createIndex(e, e.indexes[0])
        assertEquals("CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id)", sql)
    }

    @Test
    fun `id колонка помечена`() {
        val e = desc()
        assertEquals(listOf("id"), e.idColumns.map { it.fullColumnName })
    }
}

/**
 * Тесты кодирования объекта в значения.
 *
 * Проверяется, что [ValueEncoder] кладёт значения по правильным ключам:
 * именно здесь ломается всё, если путь вложенности ведётся неверно.
 */
class ValueEncoderTest {

    @Test
    fun `простые поля`() {
        val u = User(id = 0, name = "Анна", email = "a@b.c", active = false, score = 7)
        val m = ValueEncoder.encode(u, User.serializer())

        assertEquals(SqlValue.Int64(0), m["id"])
        assertEquals(SqlValue.Text("Анна"), m["name"])
        assertEquals(SqlValue.Text("a@b.c"), m["email"])
        assertEquals(SqlValue.Bool(false), m["active"])
        assertEquals(SqlValue.Int32(7), m["score"])
    }

    @Test
    fun `вложенный объект идёт с путём`() {
        val p = Person(id = 1, name = "Иван", address = Address("Москва", "Тверская"))
        val m = ValueEncoder.encode(p, Person.serializer())

        assertEquals(SqlValue.Text("Москва"), m["address.city"])
        assertEquals(SqlValue.Text("Тверская"), m["address.street"])
        assertEquals(SqlValue.Text("Иван"), m["name"])
    }

    @Test
    fun `поля вложенного не затирают родителя`() {
        // У Address нет поля name, но если бы было — путь развёл бы их.
        val p = Person(id = 1, name = "Иван", address = Address("М", "Т"))
        val m = ValueEncoder.encode(p, Person.serializer())
        assertEquals(SqlValue.Text("Иван"), m["name"])
        assertEquals(4, m.size)
    }

    @Test
    fun `перечисление кодируется именем`() {
        val color = ColorEntity(id = 1, color = Color.GREEN)
        val m = ValueEncoder.encode(color, ColorEntity.serializer())
        assertEquals(SqlValue.Text("GREEN"), m["color"])
    }
}
