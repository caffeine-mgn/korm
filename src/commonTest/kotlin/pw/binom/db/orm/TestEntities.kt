package pw.binom.db.orm

import kotlinx.serialization.Serializable

@Serializable
@TableName("users")
data class User(
    @Id
    @AutoGenerated
    val id: Long = 0,
    val name: String,
    @ColumnName("email_addr")
    val email: String,
    val active: Boolean = true,
    val score: Int = 0,
)

@Serializable
@TableName("orders")
@Index(name = "orders_user_idx", columns = ["user_id"])
data class Order(
    @Id
    val id: Long,
    @ColumnName("user_id")
    val userId: Long,
    val amount: Double,
)

@Serializable
data class Address(
    val city: String,
    val street: String,
)

@Serializable
@TableName("people")
data class Person(
    @Id
    val id: Long,
    val name: String,
    @Embedded
    @EmbeddedPrefix("home_")
    val address: Address,
)

@Serializable
@TableName("keyword_table")
data class KeywordEntity(
    @Id
    val id: Long,
    @UseQuotes
    @ColumnName("order")
    val order: Int,
)

@Serializable
@TableName("typed")
data class TypedEntity(
    @Id
    val id: Long,
    @PgColumnType("JSONB")
    val payload: String,
    @ColumnType("VARCHAR(64)")
    val code: String,
)

enum class Color { RED, GREEN, BLUE }

@Serializable
@TableName("colors")
data class ColorEntity(
    @Id
    val id: Long,
    val color: Color,
)
